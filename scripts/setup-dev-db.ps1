<#
.SYNOPSIS
  One-time (idempotent) setup of VoiceFlow's local development PostgreSQL on the D: drive.

.DESCRIPTION
  - Uses the portable PostgreSQL binaries in $PgBin (no installer, no admin rights).
  - Creates the data directory, listening on localhost only, SCRAM password auth.
  - Generates random passwords (never printed). The admin password is saved to
    $AdminSecretFile; the app connection strings are written to backend\.env (git-ignored).
  - Creates role "voiceflow" and databases "voiceflow" and "voiceflow_test".
  Safe to re-run: existing data, roles, databases and .env are left as they are.
#>
param(
    [string]$PgBin = 'D:\tools\pgsql\bin',
    [string]$DataDir = 'D:\tools\pgdata',
    [int]$Port = 5433,
    [string]$AdminSecretFile = 'D:\tools\postgres-dev-admin-password.txt'
)

$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path -Parent $PSScriptRoot
$EnvFile = Join-Path $RepoRoot 'backend\.env'

function New-Secret {
    $bytes = New-Object byte[] 24
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return -join ($bytes | ForEach-Object { $_.ToString('x2') })   # hex: URL-safe
}

function Invoke-Psql([string]$Sql, [hashtable]$Vars = @{}, [string]$Db = 'postgres') {
    $args = @('-h', 'localhost', '-p', $Port, '-U', 'postgres', '-d', $Db, '-v', 'ON_ERROR_STOP=1', '-qAt')
    foreach ($k in $Vars.Keys) { $args += @('-v', "$k=$($Vars[$k])") }
    $out = $Sql | & (Join-Path $PgBin 'psql.exe') @args
    if ($LASTEXITCODE -ne 0) { throw "psql failed (exit $LASTEXITCODE)" }
    return $out
}

# 1. Initialise the cluster once.
if (-not (Test-Path (Join-Path $DataDir 'PG_VERSION'))) {
    Write-Host "Creating PostgreSQL data directory at $DataDir"
    $adminPw = New-Secret
    $pwFile = New-TemporaryFile
    try {
        Set-Content -Path $pwFile -Value $adminPw -NoNewline -Encoding ascii
        & (Join-Path $PgBin 'initdb.exe') -D $DataDir -U postgres --pwfile=$pwFile `
            --auth=scram-sha-256 --encoding=UTF8 --no-locale | Out-Null
        if ($LASTEXITCODE -ne 0) { throw "initdb failed (exit $LASTEXITCODE)" }
    } finally {
        Remove-Item $pwFile -Force
    }
    Set-Content -Path $AdminSecretFile -Value $adminPw -NoNewline -Encoding ascii
    Write-Host "Admin password saved to $AdminSecretFile"
} else {
    Write-Host "Data directory already exists at $DataDir"
}

# 2. Start the server if it is not running (localhost only, chosen port).
& (Join-Path $PgBin 'pg_ctl.exe') status -D $DataDir *> $null
if ($LASTEXITCODE -ne 0) {
    Write-Host "Starting PostgreSQL on localhost:$Port"
    # Run pg_ctl in its own hidden console and wait only for pg_ctl. Piping its output would
    # hang (the server keeps the handle open), and sharing our console would break the server
    # when this terminal closes (new backends then fail with 0xC0000142).
    $logFile = Join-Path $DataDir 'server.log'
    $p = Start-Process -FilePath (Join-Path $PgBin 'pg_ctl.exe') -WindowStyle Hidden -PassThru -ArgumentList @(
        'start', '-D', "`"$DataDir`"", '-w', '-l', "`"$logFile`"",
        '-o', "`"-p $Port -c listen_addresses=localhost`"")
    $p.WaitForExit()
    if ($p.ExitCode -ne 0) { throw "pg_ctl start failed; see $logFile" }
} else {
    Write-Host 'PostgreSQL is already running'
}

$env:PGPASSWORD = (Get-Content $AdminSecretFile -Raw).Trim()
try {
    # 3. Application role + databases.
    $roleExists = Invoke-Psql "SELECT 1 FROM pg_roles WHERE rolname = 'voiceflow';"
    if (-not $roleExists) {
        if (Test-Path $EnvFile) {
            throw "Role 'voiceflow' is missing but $EnvFile exists. Remove the stale .env and re-run."
        }
        $appPw = New-Secret
        Invoke-Psql "CREATE ROLE voiceflow LOGIN PASSWORD :'pw';" @{ pw = $appPw } | Out-Null
        Write-Host "Created role 'voiceflow'"

        $envText = @"
# Generated by scripts/setup-dev-db.ps1 - local development only. Never commit this file.
VOICEFLOW_ENVIRONMENT=development
VOICEFLOW_DATABASE_URL=postgresql+psycopg://voiceflow:$appPw@localhost:$Port/voiceflow
VOICEFLOW_TEST_DATABASE_URL=postgresql+psycopg://voiceflow:$appPw@localhost:$Port/voiceflow_test
"@
        Set-Content -Path $EnvFile -Value $envText -Encoding utf8
        Write-Host "Wrote connection settings to $EnvFile"
    } else {
        Write-Host "Role 'voiceflow' already exists"
    }

    foreach ($db in 'voiceflow', 'voiceflow_test') {
        $dbExists = Invoke-Psql "SELECT 1 FROM pg_database WHERE datname = :'db';" @{ db = $db }
        if (-not $dbExists) {
            Invoke-Psql "CREATE DATABASE $db OWNER voiceflow ENCODING 'UTF8';" | Out-Null
            Write-Host "Created database '$db'"
        } else {
            Write-Host "Database '$db' already exists"
        }
    }
} finally {
    Remove-Item Env:PGPASSWORD -ErrorAction SilentlyContinue
}

Write-Host 'Done.'
